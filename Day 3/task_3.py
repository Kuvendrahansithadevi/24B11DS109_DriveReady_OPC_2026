import os
from google.colab import userdata
from langchain_groq import ChatGroq

os.environ["GROQ_API_KEY"] = userdata.get("Groq")
llm = ChatGroq(model="openai/gpt-oss-20b", temperature=0.3)

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE:   You are the friendly front-desk assistant for BrightSmile Dental Clinic.
FACTS:  General checkup Rs 300. Teeth cleaning Rs 1000. Tooth extraction Rs 1500.
        Consultations are by appointment only. Clinic hours are 9 AM to 7 PM, Mon to Sat.
RULES:  Never give medical diagnoses or prescribe medication. Never promise walk-in slots without checking.
        If it isn't in FACTS, say "I'll check with the doctor." Work out totals carefully.
        "Always mention exact numbers/timings from FACTS directly."
FORMAT: Under 50 words, warm, English or Telugu matching the patient."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}"),
])
chain = prompt | llm | StrOutputParser()

history = []
def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I'm Hansitha. Do you offer teeth cleaning?"))
print(ask("What's my name?"))

