import json, functools
from openai import RateLimitError, APIConnectionError

MODEL = "openai/gpt-oss-120b"
SERVICES = {"general checkup": 300, "teeth cleaning": 1000, "tooth extraction": 1500}

SYSTEM = f"""ROLE:   You are the friendly front-desk assistant for BrightSmile Dental Clinic.
FACTS:  Services with fees in rupees: {json.dumps(SERVICES)}
        Consultations are by appointment only. Clinic hours are 9 AM to 7 PM, Mon to Sat.
        Emergency slots depend on availability.
RULES:  Never give medical diagnoses or prescribe medication. Never promise a delivery time.
        If it isn't in FACTS, say "I'll check with the doctor."
        Remember the patient's name and requested service during the chat.
FORMAT: Under 50 words, warm, English or Telugu matching the patient."""

def log_call(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        result = func(*args, **kwargs)
        print(f"   [log] {func.__name__}{args} -> {result!r}")
        return result
    return wrapper

@log_call
def get_fee(service: str, sessions: int = 1) -> int:
    """Return the total fee in rupees for sessions of a service at BrightSmile Dental Clinic."""
    return SERVICES[service.lower().strip()] * sessions

history = [{"role": "system", "content": SYSTEM}]
MAX_TURNS = 8

def chat(user_text: str) -> str:
    history.append({"role": "user", "content": user_text})
    recent = [history[0]] + history[1:][-MAX_TURNS:]
    try:
        response = client.chat.completions.create(model=MODEL, messages=recent, temperature=0.3)
        reply = response.choices[0].message.content
    except RateLimitError:
        reply = "We're a little busy. Please try again in a minute."
    except APIConnectionError:
        reply = "I can't reach the server right now. Please try again shortly."
    history.append({"role": "assistant", "content": reply})
    return reply


while True:
    text = input("You: ")
    if text.lower().strip() in ("bye", "exit", "quit"):
        print("Bot: Thank you for visiting BrightSmile Dental Clinic!")
        break
    print("Bot:", chat(text))

