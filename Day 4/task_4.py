from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool

SERVICES = {"general checkup": 300, "teeth cleaning": 1000, "tooth extraction": 1500}
HOURS = {
    "monday": "9 am to 7 pm", "tuesday": "9 am to 7 pm", "wednesday": "9 am to 7 pm",
    "thursday": "9 am to 7 pm", "friday": "9 am to 7 pm", "saturday": "9 am to 7 pm",
    "sunday": "closed"
}

class Appointment(BaseModel):
    """A dental appointment taken from a patient's chat message."""
    name: str = Field(description="Patient's first name")
    service: Literal["general checkup", "teeth cleaning", "tooth extraction"] = Field(description="Dental service")
    sessions: int = Field(description="Number of sessions", ge=1)
    date: str = Field(description="Appointment date as the patient said it")
    urgent: bool = Field(description="True if the patient asked for an urgent/emergency slot")

@tool
def get_fee(service: str, sessions: int = 1) -> str:
    """Get the total fee in rupees for a number of sessions of one dental service.

    Args:
        service: Dental service, e.g. "general checkup", "teeth cleaning" or "tooth extraction"
        sessions: Number of sessions the patient wants
    """
    fee = SERVICES.get(service.lower().strip())
    if fee is None:
        return f"'{service}' is not listed. We offer: {', '.join(SERVICES)}."
    return f"{sessions} x {service} = Rs {fee * sessions}"

@tool
def is_open(day: str) -> str:
    """Check the dental clinic's opening hours for a day of the week, e.g. "sunday"."""
    hours = HOURS.get(day.lower().strip())
    if not hours:
        return f"'{day}' is not a day of the week."
    return "Closed on Sunday." if hours == "closed" else f"Open {hours} on {day}."

@tool
def log_appointment(name: str, service: str, sessions: int, date: str, urgent: bool) -> str:
    """Save a confirmed dental appointment to the Appointments sheet.
    Use only when the patient has given their name, service, sessions and appointment date."""
    try:
        appt = Appointment(name=name, service=service.lower().strip(), sessions=sessions, date=date, urgent=urgent)
    except Exception as e:
        return f"Could not save the appointment: {e}. Ask the patient to correct it."
    total = SERVICES[appt.service] * appt.sessions
    ws.append_row([appt.name, appt.service, appt.sessions, appt.date,
                   "yes" if appt.urgent else "no", total])
    return f"Saved: {appt.sessions} x {appt.service} for {appt.name} on {appt.date}, Rs {total}."

from langchain.agents import create_agent

SYSTEM = """ROLE:   You are the friendly front-desk assistant for BrightSmile Dental Clinic.
FACTS:  Consultations are by appointment only. Emergency slots depend on availability.
RULES:  Always use get_fee for fees and is_open for timings; never guess them.
        Never give medical diagnoses or prescribe medication.
        Before log_appointment, make sure you have name, service, sessions and date; ask if missing.
        After saving, read the appointment back with the total.
FORMAT: Under 60 words, warm, English or Telugu matching the patient."""

agent = create_agent(model=llm, tools=[get_fee, is_open, log_appointment], system_prompt=SYSTEM)

history = []
def chat(text: str) -> str:
    global history
    try:
        result = agent.invoke({"messages": history + [{"role": "user", "content": text}]})
        history = result["messages"]
        return history[-1].content
    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I'm a little busy. Please try again in a minute."

