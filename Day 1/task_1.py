# Initialize the LLM with a valid Groq model (e.g., llama-3.3-70b-versatile)
llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0
)

SYSTEM = """You are the front-desk assistant for BrightSmile Dental Clinic.
Facts: consultations are by appointment only; clinic hours are 9 AM to 7 PM, Monday to Saturday; emergency slots are subject to availability.
Rules: never give medical diagnoses or prescribe medication; if you do not know, say so.
Format: reply warmly and concisely in under 60 words."""

def ask(question):
    return llm.invoke([("system", SYSTEM), ("human", question)]).content

print(ask("I have severe tooth pain, can I walk in right now without an appointment and what tablet should I take?"))



print(ask("Are you open on Sundays for a routine teeth cleaning?"))

print(ask("Why are my gums bleeding when I brush, and how much does a root canal cost?"))



