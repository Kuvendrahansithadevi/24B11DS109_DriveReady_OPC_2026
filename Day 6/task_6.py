from typing import Literal
from typing_extensions import TypedDict
from pydantic import BaseModel, Field
from langgraph.graph import StateGraph, START, END

class ClinicState(TypedDict):
    message: str
    intent: str
    reply: str

class Intent(BaseModel):
    intent: Literal["appointment", "faq", "other"] = Field(
        description=(
            "appointment = wants to book, schedule, or request a dental appointment or checkup slot; "
            "faq = asks about treatment fees, clinic hours, Sunday status, location, payment methods, "
            "discounts, or clinic policies; "
            "other = greetings (hi, hello, good morning) or anything unrelated to the dental clinic"
        )
    )

# Instruct Groq explicitly to respond in valid JSON matching the Intent schema structure
classifier = llm.with_structured_output(Intent, method="json_mode")

from langchain.agents import create_agent

FAQ_PROMPT = """You answer questions for BrightSmile Dental Clinic.
Use get_fee for service fees, is_open for clinic hours, and search_clinic_faq for clinic policies.
Never guess or prescribe medication. If the answer isn't found, say "I'll check with the doctor."
Write numbers plainly without commas (e.g., Rs 1000). Under 50 words, English or Telugu matching the patient."""

APPOINTMENT_PROMPT = """You book appointments for BrightSmile Dental Clinic.
Use get_fee for treatment totals. Before log_appointment, make sure you have name, service, sessions and date;
ask for anything missing. After saving, read the appointment back with the total.
Under 60 words, English or Telugu matching the patient."""

faq_agent = create_agent(
    model=llm,
    tools=[search_clinic_faq, get_fee, is_open],
    system_prompt=FAQ_PROMPT
)

appointment_agent = create_agent(
    model=llm,
    tools=[get_fee, log_appointment],
    system_prompt=APPOINTMENT_PROMPT
)

def classify(state: ClinicState) -> dict:
    # Groq strictly requires the word 'json' to be in the prompt message when using json_object format.
    prompt = f"""You are a routing assistant. Respond strictly using JSON format.

Classify the following user message into one of these intents: 'appointment', 'faq', or 'other'.
Return a valid JSON object matching this schema: {{"intent": "string"}}

User Message: {state['message']}"""
    return {"intent": classifier.invoke(prompt).intent}

def ask_agent(agent, message: str) -> str:
    result = agent.invoke({"messages": [{"role": "user", "content": message}]})
    return result["messages"][-1].content

def answer_faq(state: ClinicState) -> dict:
    return {"reply": ask_agent(faq_agent, state["message"])}

def book_appointment(state: ClinicState) -> dict:
    return {"reply": ask_agent(appointment_agent, state["message"])}

def other(state: ClinicState) -> dict:
    return {
        "reply": "Hello from BrightSmile Dental Clinic! I can help with treatment fees, clinic hours, policies, and booking appointments."
    }

def route(state: ClinicState) -> str:
    return state["intent"]

builder = StateGraph(ClinicState)
builder.add_node("classify", classify)
builder.add_node("faq", answer_faq)
builder.add_node("appointment", book_appointment)
builder.add_node("other", other)

builder.add_edge(START, "classify")
builder.add_conditional_edges(
    "classify",
    route,
    {"appointment": "appointment", "faq": "faq", "other": "other"}
)
builder.add_edge("faq", END)
builder.add_edge("appointment", END)
builder.add_edge("other", END)

graph = builder.compile()
